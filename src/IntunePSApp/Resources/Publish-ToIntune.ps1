<#
.SYNOPSIS
    Publishes the package of this folder to Microsoft Intune as a Windows app (Win32).  [PREVIEW]

.DESCRIPTION
    Generated by J365 IntunePSApp (https://github.com/sesantanajr/J365-IntunePSApp).

    Everything is read from intune-app.json, in this folder: name, command lines, detection script,
    requirements and icon. The upload is done by the community PowerShell module IntuneWin32App
    (https://github.com/MSEndpointMgr/IntuneWin32App) with YOUR sign-in: no credential is stored by
    this script or by J365 IntunePSApp.

    Requirements
      - Windows PowerShell 5.1.
      - An app registration in Microsoft Entra ID (public client, redirect URI http://localhost) with the
        delegated permission DeviceManagementApps.ReadWrite.All (Microsoft Graph).
        Step by step: https://github.com/sesantanajr/J365-IntunePSApp/blob/main/docs/INTUNE-PUBLISH.md
      - An account allowed to create apps in Intune (for example the Intune Administrator role).

    The app is created WITHOUT assignments. Review it in the Intune admin center and assign it to a
    pilot group before a broad deployment.

.PARAMETER TenantId
    Tenant ID (GUID) or domain, for example contoso.onmicrosoft.com.

.PARAMETER ClientId
    Application (client) ID of your app registration.

.PARAMETER DeviceCode
    Signs in with a device code instead of the browser window.

.PARAMETER ValidateOnly
    Checks the files and shows what would be published, without connecting to Intune.

.PARAMETER Force
    Does not ask for confirmation (module installation and app creation).

.EXAMPLE
    .\Publish-ToIntune.ps1 -TenantId contoso.onmicrosoft.com -ClientId 00000000-0000-0000-0000-000000000000

.EXAMPLE
    .\Publish-ToIntune.ps1 -ValidateOnly
#>
[CmdletBinding()]
param
(
    [string]$TenantId,
    [string]$ClientId,
    [switch]$DeviceCode,
    [switch]$ValidateOnly,
    [switch]$Force
)

$ErrorActionPreference = 'Stop'
$ModuleName = 'IntuneWin32App'
$MinimumModuleVersion = [version]'1.4.0'

function Write-Step([string]$Text) { Write-Host ('> ' + $Text) -ForegroundColor Cyan }
function Write-Ok([string]$Text) { Write-Host ('  OK     ' + $Text) -ForegroundColor Green }
function Write-Note([string]$Text) { Write-Host ('  ' + $Text) -ForegroundColor Yellow }

# Returns the first preferred value accepted by a parameter that has a ValidateSet.
# This keeps the script working when a module version names a value slightly differently.
function Resolve-SetValue
{
    param([string]$Command, [string]$Parameter, [string[]]$Preferred)

    $cmd = Get-Command -Name $Command -ErrorAction Stop
    $valid = @()
    if ($cmd.Parameters.ContainsKey($Parameter))
    {
        foreach ($attribute in $cmd.Parameters[$Parameter].Attributes)
        {
            if ($attribute -is [System.Management.Automation.ValidateSetAttribute]) { $valid = @($attribute.ValidValues) }
        }
    }
    if ($valid.Count -eq 0) { return $Preferred[0] }
    foreach ($wanted in $Preferred)
    {
        foreach ($value in $valid) { if ($value -ieq $wanted) { return $value } }
    }
    return $null
}

try
{
    Write-Host ''
    Write-Host 'J365 IntunePSApp - Publish to Intune (preview)' -ForegroundColor White
    Write-Host ''

    # ---------------------------------------------------------------- package metadata
    $here = Split-Path -Parent $MyInvocation.MyCommand.Path
    $metadataPath = Join-Path $here 'intune-app.json'
    if (-not (Test-Path -LiteralPath $metadataPath)) { throw 'intune-app.json was not found next to this script.' }
    $app = Get-Content -LiteralPath $metadataPath -Raw -Encoding UTF8 | ConvertFrom-Json

    foreach ($required in 'displayName', 'intuneWinFile', 'detectionScript', 'installCommandLine', 'uninstallCommandLine')
    {
        if ([string]::IsNullOrWhiteSpace([string]$app.$required)) { throw ('intune-app.json is incomplete: "' + $required + '" is empty.') }
    }

    $intuneWin = Join-Path $here $app.intuneWinFile
    $detection = Join-Path $here $app.detectionScript
    foreach ($file in $intuneWin, $detection)
    {
        if (-not (Test-Path -LiteralPath $file -PathType Leaf)) { throw ('File not found: ' + $file) }
    }
    $icon = $null
    if (-not [string]::IsNullOrWhiteSpace([string]$app.icon))
    {
        $candidate = Join-Path $here $app.icon
        if (Test-Path -LiteralPath $candidate -PathType Leaf) { $icon = $candidate }
    }

    if (-not [string]::IsNullOrWhiteSpace([string]$app.intuneWinSha256))
    {
        $hash = (Get-FileHash -LiteralPath $intuneWin -Algorithm SHA256).Hash
        if ($hash -ne $app.intuneWinSha256)
        {
            throw 'The .intunewin file does not match the SHA256 recorded when it was generated. Generate the package again.'
        }
    }

    $publisher = [string]$app.publisher
    if ([string]::IsNullOrWhiteSpace($publisher)) { $publisher = [string]$app.displayName }
    $description = [string]$app.description
    if ([string]::IsNullOrWhiteSpace($description)) { $description = [string]$app.displayName }
    $experience = 'system'
    if ([string]$app.installExperience -ieq 'user') { $experience = 'user' }
    $iconLabel = '(none)'
    if ($icon) { $iconLabel = [string]$app.icon }

    Write-Host ('  App             : ' + $app.displayName)
    Write-Host ('  Publisher       : ' + $publisher)
    Write-Host ('  Package         : ' + $app.intuneWinFile + '  (' + [math]::Round((Get-Item -LiteralPath $intuneWin).Length / 1MB, 1) + ' MB)')
    Write-Host ('  Install         : ' + $app.installCommandLine)
    Write-Host ('  Uninstall       : ' + $app.uninstallCommandLine)
    Write-Host ('  Install context : ' + $experience)
    Write-Host ('  Architecture    : ' + $app.architecture)
    Write-Host ('  Minimum Windows : ' + $app.minimumSupportedWindowsRelease)
    Write-Host ('  Detection       : ' + $app.detectionScript)
    Write-Host ('  Icon            : ' + $iconLabel)
    Write-Host ''

    if ($ValidateOnly)
    {
        Write-Ok 'Files and metadata are valid. Nothing was sent to Intune (-ValidateOnly).'
        exit 0
    }

    # ---------------------------------------------------------------- module
    Write-Step ('Checking the PowerShell module ' + $ModuleName + '...')
    $module = Get-Module -ListAvailable -Name $ModuleName | Sort-Object -Property Version -Descending | Select-Object -First 1
    if (-not $module)
    {
        Write-Note ('The module ' + $ModuleName + ' (community project by MSEndpointMgr) is required and is not installed.')
        if (-not $Force)
        {
            $answer = Read-Host '  Install it now from the PowerShell Gallery, for the current user only? (Y/N)'
            if ($answer -notmatch '^\s*(y|s)') { throw 'The module was not installed. Nothing was published.' }
        }
        [Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12
        Install-Module -Name $ModuleName -Scope CurrentUser -Force -AllowClobber
        $module = Get-Module -ListAvailable -Name $ModuleName | Sort-Object -Property Version -Descending | Select-Object -First 1
        if (-not $module) { throw ('The module ' + $ModuleName + ' could not be installed.') }
    }
    if ($module.Version -lt $MinimumModuleVersion)
    {
        throw ('The installed ' + $ModuleName + ' ' + $module.Version + ' is too old. Run: Update-Module ' + $ModuleName)
    }
    Import-Module -Name $ModuleName -ErrorAction Stop
    Write-Ok ($ModuleName + ' ' + $module.Version)

    # ---------------------------------------------------------------- sign-in
    if ([string]::IsNullOrWhiteSpace($TenantId)) { $TenantId = Read-Host 'Tenant ID or domain (for example contoso.onmicrosoft.com)' }
    if ([string]::IsNullOrWhiteSpace($ClientId)) { $ClientId = Read-Host 'Application (client) ID of your Entra app registration' }
    if ([string]::IsNullOrWhiteSpace($TenantId) -or [string]::IsNullOrWhiteSpace($ClientId)) { throw 'TenantId and ClientId are required.' }

    Write-Step 'Signing in to Microsoft Graph (a sign-in window or code will be shown)...'
    $connectCommand = Get-Command -Name 'Connect-MSIntuneGraph' -ErrorAction Stop
    $connect = @{ TenantID = $TenantId.Trim(); ClientID = $ClientId.Trim() }
    if ($DeviceCode)
    {
        if ($connectCommand.Parameters.ContainsKey('DeviceCode')) { $connect['DeviceCode'] = $true }
        else { Write-Note 'This module version has no -DeviceCode option: using the interactive sign-in.' }
    }
    elseif ($connectCommand.Parameters.ContainsKey('Interactive')) { $connect['Interactive'] = $true }
    $null = Connect-MSIntuneGraph @connect
    Write-Ok ('Connected to ' + $TenantId.Trim())

    # ---------------------------------------------------------------- rules
    Write-Step 'Preparing the detection and requirement rules...'
    $detectionRule = New-IntuneWin32AppDetectionRuleScript -ScriptFile $detection -EnforceSignatureCheck $false -RunAs32Bit $false

    $architecture = Resolve-SetValue -Command 'New-IntuneWin32AppRequirementRule' -Parameter 'Architecture' -Preferred @([string]$app.architecture, 'x64x86', 'All', 'x64')
    $minimumOs = Resolve-SetValue -Command 'New-IntuneWin32AppRequirementRule' -Parameter 'MinimumSupportedWindowsRelease' -Preferred @([string]$app.minimumSupportedWindowsRelease, 'W10_1607', '1607')
    if (-not $architecture -or -not $minimumOs)
    {
        throw ('This version of ' + $ModuleName + ' does not accept the requirement values of the package. Run: Update-Module ' + $ModuleName)
    }
    $requirementRule = New-IntuneWin32AppRequirementRule -Architecture $architecture -MinimumSupportedWindowsRelease $minimumOs
    Write-Ok ('Requirements: ' + $architecture + ', ' + $minimumOs)

    # ---------------------------------------------------------------- app
    $addCommand = Get-Command -Name 'Add-IntuneWin32App' -ErrorAction Stop
    $restart = Resolve-SetValue -Command 'Add-IntuneWin32App' -Parameter 'RestartBehavior' -Preferred @([string]$app.restartBehavior, 'basedOnReturnCode')
    if (-not $restart) { $restart = 'basedOnReturnCode' }

    $parameters = @{
        FilePath             = $intuneWin
        DisplayName          = [string]$app.displayName
        Description          = $description
        Publisher            = $publisher
        InstallCommandLine   = [string]$app.installCommandLine
        UninstallCommandLine = [string]$app.uninstallCommandLine
        InstallExperience    = $experience
        RestartBehavior      = $restart
        DetectionRule        = $detectionRule
        RequirementRule      = $requirementRule
    }
    # Optional values are only sent when the installed module version knows the parameter.
    $optional = @{}
    if (-not [string]::IsNullOrWhiteSpace([string]$app.appVersion)) { $optional['AppVersion'] = [string]$app.appVersion }
    if (-not [string]::IsNullOrWhiteSpace([string]$app.notes)) { $optional['Notes'] = [string]$app.notes }
    if ([string]$app.informationUrl -match '^https?://') { $optional['InformationURL'] = [string]$app.informationUrl }
    if ([int]$app.maximumInstallationTimeInMinutes -gt 0) { $optional['MaximumInstallationTimeInMinutes'] = [int]$app.maximumInstallationTimeInMinutes }
    if ($app.allowAvailableUninstall -eq $true) { $optional['AllowAvailableUninstall'] = $true }
    foreach ($name in $optional.Keys)
    {
        if ($addCommand.Parameters.ContainsKey($name)) { $parameters[$name] = $optional[$name] }
    }
    if ($icon -and $addCommand.Parameters.ContainsKey('Icon')) { $parameters['Icon'] = New-IntuneWin32AppIcon -FilePath $icon }

    if (-not $Force)
    {
        Write-Host ''
        $answer = Read-Host ('Create the app "' + $app.displayName + '" in the tenant ' + $TenantId.Trim() + ' now? (Y/N)')
        if ($answer -notmatch '^\s*(y|s)')
        {
            Write-Note 'Cancelled. Nothing was published.'
            exit 0
        }
    }

    Write-Step 'Uploading the package to Intune (this can take a few minutes)...'
    $result = Add-IntuneWin32App @parameters
    if (-not $result -or [string]::IsNullOrWhiteSpace([string]$result.id)) { throw 'Intune did not return the new app. Check the messages above.' }

    Write-Host ''
    Write-Ok ('App created: ' + $result.displayName)
    Write-Host ('         id: ' + $result.id)
    Write-Host ''
    Write-Host 'Next steps' -ForegroundColor White
    Write-Host '  1. Open https://intune.microsoft.com > Apps > Windows and review the new app.'
    Write-Host '  2. Assign it to a pilot group before a broad deployment (it was created without assignments).'
    Write-Host ''
    exit 0
}
catch
{
    Write-Host ''
    Write-Host ('  ERROR  ' + $_.Exception.Message) -ForegroundColor Red
    Write-Host ''
    exit 1
}
