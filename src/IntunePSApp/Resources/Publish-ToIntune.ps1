function Set-Token($Response)
{
    $script:Token = @{
        AccessToken  = [string]$Response.access_token
        RefreshToken = [string]$Response.refresh_token
        ExpiresAt    = (Get-Date).AddSeconds([int]$Response.expires_in)
    }
}

function Invoke-TokenRequest([hashtable]$Fields, [switch]$AllowPending)
{
    $answer = Invoke-Http -Method 'POST' -Url ($LoginUrl.TrimEnd('/') + '/' + $TenantId + '/oauth2/v2.0/token') -Body (ConvertTo-FormBody $Fields) -ContentType 'application/x-www-form-urlencoded'
    $data = $null
    try { $data = $answer.Text | ConvertFrom-Json } catch { }
    if ($answer.Status -eq 200 -and $data -and $data.access_token) { return $data }
    if ($AllowPending -and $data -and ($data.error -eq 'authorization_pending' -or $data.error -eq 'slow_down')) { return $data }
    $description = 'HTTP ' + $answer.Status
    if ($data -and $data.error_description) { $description = ([string]$data.error_description -split "`r?`n")[0] }
    $help = Get-SignInHelp $description
    if ($help) { throw ('Sign-in failed. ' + $help + ' [' + $description + ']') }
    throw ('Sign-in failed: ' + $description)
}

function ConvertTo-Base64Url([byte[]]$Bytes) { return [Convert]::ToBase64String($Bytes).TrimEnd('=').Replace('+', '-').Replace('/', '_') }

# Browser sign-in: authorization code with PKCE, answered on a local port.
function Connect-WithBrowser
{
    $random = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    $bytes = New-Object byte[] 32
    $random.GetBytes($bytes)
    $verifier = ConvertTo-Base64Url $bytes
    $sha = [System.Security.Cryptography.SHA256]::Create()
    $challenge = ConvertTo-Base64Url ($sha.ComputeHash([System.Text.Encoding]::ASCII.GetBytes($verifier)))
    $random.GetBytes($bytes)
    $state = ConvertTo-Base64Url $bytes

    $probe = New-Object System.Net.Sockets.TcpListener([System.Net.IPAddress]::Loopback, 0)
    $probe.Start()
    $port = $probe.LocalEndpoint.Port
    $probe.Stop()
    # Same form as the registration ("http://localhost"): Entra ID accepts any port on the loopback address.
    $redirect = 'http://localhost:' + $port
    $listener = New-Object System.Net.HttpListener
    $listener.Prefixes.Add($redirect + '/')
    $listener.Start()
    try
    {
        $query = @{
            client_id = $ClientId; response_type = 'code'; redirect_uri = $redirect; response_mode = 'query'; scope = $Scope
            state = $state; code_challenge = $challenge; code_challenge_method = 'S256'; prompt = 'select_account'
        }
        $pairs = foreach ($name in $query.Keys) { $name + '=' + [uri]::EscapeDataString([string]$query[$name]) }
        $authorize = $LoginUrl.TrimEnd('/') + '/' + $TenantId + '/oauth2/v2.0/authorize?' + ($pairs -join '&')
        Write-Note 'A browser window opens for the sign-in. This script waits up to 5 minutes.'
        Start-Process $authorize

        $pending = $listener.BeginGetContext($null, $null)
        if (-not $pending.AsyncWaitHandle.WaitOne(300000)) { throw 'The sign-in was not completed within 5 minutes (was the browser window closed?).' }
        $context = $listener.EndGetContext($pending)
        $answer = $context.Request.QueryString
        $page = '<html><body style="font-family:Segoe UI,sans-serif;margin:48px"><h2>J365 IntunePSApp</h2><p>The sign-in was received. You can close this tab and return to the PowerShell window.</p></body></html>'
        $pageBytes = [System.Text.Encoding]::UTF8.GetBytes($page)
        $context.Response.ContentType = 'text/html; charset=utf-8'
        $context.Response.OutputStream.Write($pageBytes, 0, $pageBytes.Length)
        $context.Response.Close()
    }
    finally { $listener.Stop(); $listener.Close() }

    if ($answer['error'])
    {
        $description = ([string]$answer['error_description'] -split "`r?`n")[0]
        $help = Get-SignInHelp $description
        if ($help) { throw ('Sign-in failed. ' + $help + ' [' + $description + ']') }
        throw ('Sign-in failed: ' + $answer['error'] + ' ' + $description)
    }
    if ([string]$answer['state'] -ne $state -or -not $answer['code']) { throw 'Sign-in failed: unexpected answer from the browser.' }
    Set-Token (Invoke-TokenRequest @{ grant_type = 'authorization_code'; client_id = $ClientId; code = $answer['code']; redirect_uri = $redirect; code_verifier = $verifier; scope = $Scope })
}

function Connect-WithDeviceCode
{
    $answer = Invoke-Http -Method 'POST' -Url ($LoginUrl.TrimEnd('/') + '/' + $TenantId + '/oauth2/v2.0/devicecode') -Body (ConvertTo-FormBody @{ client_id = $ClientId; scope = $Scope }) -ContentType 'application/x-www-form-urlencoded'
    $data = $null
    try { $data = $answer.Text | ConvertFrom-Json } catch { }
    if ($answer.Status -ne 200 -or -not $data -or -not $data.device_code)
    {
        $description = 'HTTP ' + $answer.Status
        if ($data -and $data.error_description) { $description = ([string]$data.error_description -split "`r?`n")[0] }
        $help = Get-SignInHelp $description
        if ($help) { throw ('Sign-in failed. ' + $help + ' [' + $description + ']') }
        throw ('Sign-in failed: ' + $description)
    }
    Write-Host ''
    Write-Host ('  ' + $data.message) -ForegroundColor White
    Write-Host ''
    $interval = [Math]::Max(1, [int]$data.interval)
    $deadline = (Get-Date).AddSeconds([int]$data.expires_in)
    while ((Get-Date) -lt $deadline)
    {
        Start-Sleep -Seconds $interval
        $token = Invoke-TokenRequest @{ grant_type = 'urn:ietf:params:oauth:grant-type:device_code'; client_id = $ClientId; device_code = $data.device_code } -AllowPending
        if ($token.access_token) { Set-Token $token; return }
        if ($token.error -eq 'slow_down') { $interval += 5 }
    }
    throw 'The code expired before the sign-in was completed.'
}


# App-only sign-in with the certificate of this computer (created by J365 IntunePSApp; its key never leaves the TPM or
# the Windows key store): a short assertion signed with the key. No user, no browser and no secret.
function Connect-WithCertificate
{
    $thumbprint = ($CertificateThumbprint -replace '[^0-9A-Fa-f]', '').ToUpperInvariant()
    # The store of the current user, read through .NET: no dependency on the Cert: drive of PowerShell.
    $certificate = $null
    $store = New-Object System.Security.Cryptography.X509Certificates.X509Store('My', 'CurrentUser')
    $store.Open('ReadOnly')
    try { $certificate = @($store.Certificates.Find('FindByThumbprint', $thumbprint, $false)) | Where-Object { $_.HasPrivateKey } | Select-Object -First 1 }
    finally { $store.Close() }
    if (-not $certificate -or -not $certificate.HasPrivateKey) { throw ('The certificate ' + $thumbprint + ' was not found with its private key for this Windows user (Cert:\CurrentUser\My). Connect again with the certificate in J365 IntunePSApp.') }
    if ($certificate.NotAfter -le (Get-Date)) { throw ('The certificate ' + $thumbprint + ' expired on ' + $certificate.NotAfter.ToString('yyyy-MM-dd') + '. Connect again with the certificate in J365 IntunePSApp.') }
    $rsa = [System.Security.Cryptography.X509Certificates.RSACertificateExtensions]::GetRSAPrivateKey($certificate)
    if (-not $rsa) { throw 'The key of the certificate cannot sign (an RSA key is required).' }
    $sha256 = [System.Security.Cryptography.SHA256]::Create()
    $x5tS256 = ConvertTo-Base64Url ($sha256.ComputeHash($certificate.RawData))
    $now = [DateTimeOffset]::UtcNow.ToUnixTimeSeconds()
    $audience = $LoginUrl.TrimEnd('/') + '/' + $TenantId + '/oauth2/v2.0/token'
    $payload = '{"aud":"' + $audience + '","iss":"' + $ClientId + '","sub":"' + $ClientId + '","jti":"' + [guid]::NewGuid().ToString() + '","nbf":' + ($now - 60) + ',"iat":' + $now + ',"exp":' + ($now + 600) + '}'
    $encodedPayload = ConvertTo-Base64Url ([System.Text.Encoding]::UTF8.GetBytes($payload))
    $assertion = $null
    try
    {
        # PS256 with the SHA-256 thumbprint, as Microsoft asks. Entra ID checks it with a salt as long as the hash: the
        # signature is checked here first, and a key that signs PSS another way (some TPMs) uses RS256.
        $header = ConvertTo-Base64Url ([System.Text.Encoding]::UTF8.GetBytes('{"alg":"PS256","typ":"JWT","x5t#S256":"' + $x5tS256 + '"}'))
        $unsigned = $header + '.' + $encodedPayload
        $data = [System.Text.Encoding]::ASCII.GetBytes($unsigned)
        $signature = $rsa.SignData($data, [System.Security.Cryptography.HashAlgorithmName]::SHA256, [System.Security.Cryptography.RSASignaturePadding]::Pss)
        $public = [System.Security.Cryptography.X509Certificates.RSACertificateExtensions]::GetRSAPublicKey($certificate)
        if ($public.VerifyData($data, $signature, [System.Security.Cryptography.HashAlgorithmName]::SHA256, [System.Security.Cryptography.RSASignaturePadding]::Pss)) { $assertion = $unsigned + '.' + (ConvertTo-Base64Url $signature) }
    }
    catch { }
    if (-not $assertion)
    {
        # RS256, which Entra ID also accepts.
        $x5t = ConvertTo-Base64Url ($certificate.GetCertHash())
        $header = ConvertTo-Base64Url ([System.Text.Encoding]::UTF8.GetBytes('{"alg":"RS256","typ":"JWT","x5t":"' + $x5t + '","x5t#S256":"' + $x5tS256 + '"}'))
        $unsigned = $header + '.' + $encodedPayload
        $signature = $rsa.SignData([System.Text.Encoding]::ASCII.GetBytes($unsigned), [System.Security.Cryptography.HashAlgorithmName]::SHA256, [System.Security.Cryptography.RSASignaturePadding]::Pkcs1)
        $assertion = $unsigned + '.' + (ConvertTo-Base64Url $signature)
    }
    Set-Token (Invoke-TokenRequest @{
        grant_type = 'client_credentials'; client_id = $ClientId; scope = ($GraphUrl.TrimEnd('/') + '/.default')
        client_assertion_type = 'urn:ietf:params:oauth:client-assertion-type:jwt-bearer'; client_assertion = $assertion
    })
}

# A long upload can outlive the access token: it is renewed when 5 minutes are left.
function Get-AccessToken
{
    if (-not $script:Token) { throw 'Not signed in.' }
    if ((Get-Date) -gt $script:Token.ExpiresAt.AddMinutes(-5))
    {
        # The application signs a new assertion; a user session is renewed with its refresh token.
        if ($CertificateThumbprint) { Connect-WithCertificate; return $script:Token.AccessToken }
        if (-not $script:Token.RefreshToken) { throw 'The sign-in expired and cannot be renewed. Run the script again.' }
        Set-Token (Invoke-TokenRequest @{ grant_type = 'refresh_token'; client_id = $ClientId; refresh_token = $script:Token.RefreshToken; scope = $Scope })
    }
    return $script:Token.AccessToken
}

# ---------------------------------------------------------------- Microsoft Graph

function Invoke-Graph
{
    # -NoRetry: only a throttled request (HTTP 429, never processed) is sent again. For the creation of the app: a
    # time-out may come after Intune created it, and a second request would create a second app.
    param([string]$Method, [string]$Path, $Body, [switch]$NoRetry)

    $url = $GraphUrl.TrimEnd('/') + '/beta' + $Path
    $bytes = $null
    if ($null -ne $Body) { $bytes = [System.Text.Encoding]::UTF8.GetBytes(($Body | ConvertTo-Json -Depth 12 -Compress)) }
    for ($attempt = 1; ; $attempt++)
    {
        $token = Get-AccessToken
        try { $answer = Invoke-Http -Method $Method -Url $url -Headers @{ Authorization = 'Bearer ' + $token } -Body $bytes -ContentType 'application/json' }
        catch
        {
            # No answer at all (network, proxy, time-out): a read is safe to ask again.
            if ($Method -ne 'GET' -or $attempt -ge 6) { throw }
            Write-Note ($_.Exception.Message + ' - trying again in ' + (5 * $attempt) + ' s...')
            Wait-Seconds (5 * $attempt)
            continue
        }
        if ($answer.Status -ge 200 -and $answer.Status -lt 300)
        {
            if ([string]::IsNullOrWhiteSpace($answer.Text)) { return $null }
            return ($answer.Text | ConvertFrom-Json)
        }
        # Throttling and temporary service errors are retried, as Microsoft Graph asks (a read also after a 500 or 502).
        $retry = ($answer.Status -eq 429) -or (-not $NoRetry -and ($answer.Status -eq 503 -or $answer.Status -eq 504)) -or ($Method -eq 'GET' -and ($answer.Status -eq 500 -or $answer.Status -eq 502))
        if ($retry -and $attempt -lt 6)
        {
            $wait = $answer.RetryAfter
            if ($wait -le 0) { $wait = 5 * $attempt }
            Write-Note ('Microsoft Graph asked to wait ' + $wait + ' s (HTTP ' + $answer.Status + ')...')
            Wait-Seconds ([Math]::Min($wait, 120))
            continue
        }
        $message = ''
        $code = ''
        try { $failure = $answer.Text | ConvertFrom-Json; $message = [string]$failure.error.message; $code = [string]$failure.error.code } catch { }
        # Intune wraps its own error as JSON in the message, sometimes twice: every level is opened, and its sentence and
        # the activity id for support are kept (not its internal address, nor an empty operation id).
        for ($depth = 0; $depth -lt 4 -and $message.TrimStart().StartsWith('{'); $depth++)
        {
            $inner = ''
            try { $inner = [string](($message | ConvertFrom-Json).Message) } catch { }
            if (-not $inner -and $message -match '"[Mm]essage"\s*:\s*"((?:[^"\\]|\\.)*)') { try { $inner = [regex]::Unescape($Matches[1]) } catch { $inner = $Matches[1] } }
            if (-not $inner) { break }
            $message = $inner.Trim()
        }
        $cut = $message.IndexOf(' - Url:')
        if ($cut -gt 0) { $message = $message.Substring(0, $cut) }
        $message = $message -replace '\s*-?\s*Operation ID \(for customer support\):\s*0{8}-0{4}-0{4}-0{4}-0{12}', ''
        if (-not $message) { $message = $answer.Text }
        if ($message.Length -gt 400) { $message = $message.Substring(0, 400) }
        $hint = ''
        if ($answer.Status -eq 401 -and $code -eq 'InvalidAuthenticationToken') { $hint = 'Microsoft Graph did not accept the sign-in: run the publication again.' }
        elseif ($answer.Status -eq 401 -or $answer.Status -eq 403 -or ($answer.Status -eq 400 -and $message -match 'not applicable to target tenant'))
        {
            # Microsoft Graph accepted the token and Intune refused the caller. A tenant without an active Intune
            # subscription refuses everyone, whatever the connection (HTTP 401, or 400 "Request not applicable to target tenant").
            if ($CertificateThumbprint) { $hint = 'Intune refused the application. Check that the tenant has an active Microsoft Intune subscription (Microsoft 365 admin center > Billing > Your products; a trial that ended gives the same answer), then that the app registration has the application permission DeviceManagementApps.ReadWrite.All with admin consent.' }
            else { $hint = 'Intune refused your account. Check that the tenant has an active Microsoft Intune subscription, that an Intune role is active now (Intune Administrator or Global Administrator; with PIM, activate it first), and that your account has an Intune license unless "Allow access to unlicensed admins" is on. Connecting with the app certificate does not depend on the role or license of an account.' }
        }
        $status = [string]$answer.Status
        if ($code) { $status += ' (' + $code + ')' }
        # The answer on the first line, what to check on the second (J365 IntunePSApp shows its own explanation instead).
        $text = 'Microsoft Graph answered HTTP ' + $status + ' to ' + $Method + ' ' + ($Path -split '\?')[0] + ': ' + $message
        if ($hint) { $text += "`n" + $hint }
        throw $text
    }
}

# Waits until Intune finishes a step of the content file (uploadState ends with Success).
function Wait-FileState([string]$FilePath, [string]$Stage, [int]$Minutes)
{
    $deadline = (Get-Date).AddMinutes($Minutes)
    while ((Get-Date) -lt $deadline)
    {
        Assert-NotCancelled
        $file = Invoke-Graph -Method 'GET' -Path $FilePath
        $state = [string]$file.uploadState
        if ($state -eq ($Stage + 'Success')) { return $file }
        if ($state -eq ($Stage + 'Failed') -or $state -eq ($Stage + 'TimedOut') -or $state -eq 'error') { throw ('Intune reported "' + $state + '" for the content of the app.') }
        Start-Sleep -Seconds 3
    }
    throw ('Intune did not finish "' + $Stage + '" within ' + $Minutes + ' minutes.')
}

# The upload address of the content (a SAS link of Azure Storage) is valid for a limited time: it is renewed when it is
# 7 minutes old, and at once after Azure Storage refused it.
function Update-UploadAddress([switch]$Force)
{
    if (-not $Force -and ((Get-Date) - $script:SasIssued).TotalMinutes -lt 7) { return }
    $null = Invoke-Graph -Method 'POST' -Path ($script:FilePath + '/renewUpload') -Body @{}
    $renewed = Wait-FileState -FilePath $script:FilePath -Stage 'azureStorageUriRenewal' -Minutes 10
    $script:SasUri = [string]$renewed.azureStorageUri
    $script:SasIssued = Get-Date
}

# One PUT to Azure Storage. A dropped network or a busy service is asked again: up to 8 attempts, 5 to 30 s apart (or
# what Retry-After asks), with a fresh upload address when it is old or was refused.
function Invoke-Storage([string]$Query, [byte[]]$Data, [string]$ContentType, [hashtable]$Headers, [string]$What)
{
    for ($attempt = 1; ; $attempt++)
    {
        Assert-NotCancelled
        $failure = ''
        $wait = 0
        $refused = $false
        $final = $false
        try
        {
            $answer = Invoke-Http -Method 'PUT' -Url ($script:SasUri + $Query) -Headers $Headers -Body $Data -ContentType $ContentType -TimeoutSeconds 600
            if ($answer.Status -eq 201) { return }
            $failure = 'HTTP ' + $answer.Status
            $wait = $answer.RetryAfter
            $refused = ($answer.Status -eq 403)
            # A request Azure Storage rejects for what it carries would be rejected again.
            $final = ($answer.Status -ge 400 -and $answer.Status -lt 500 -and @(403, 408, 429) -notcontains $answer.Status)
        }
        catch { $failure = $_.Exception.Message }
        if ($final -or $attempt -ge 8) { throw ($What + ' failed after ' + $attempt + ' attempt(s): ' + $failure) }
        if ($wait -le 0) { $wait = Get-Random -Minimum 5 -Maximum 31 }
        Write-Note ($What + ': ' + $failure + ' - trying again in ' + $wait + ' s...')
        Wait-Seconds ([Math]::Min($wait, 60))
        try { Update-UploadAddress -Force:$refused }
        catch { Write-Note ('The upload address could not be renewed: ' + $_.Exception.Message) }
    }
}

