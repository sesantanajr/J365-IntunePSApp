        'W10_1607' = '1607'; 'W10_1703' = '1703'; 'W10_1709' = '1709'; 'W10_1803' = '1803'; 'W10_1809' = '1809'; 'W10_1903' = '1903'
        'W10_1909' = '1909'; 'W10_2004' = '2004'; 'W10_20H2' = '2H20'; 'W10_21H1' = '21H1'; 'W10_21H2' = 'Windows10_21H2'
        'W10_22H2' = 'Windows10_22H2'; 'W11_21H2' = 'Windows11_21H2'; 'W11_22H2' = 'Windows11_22H2'; 'W11_23H2' = 'Windows11_23H2'
    }
    $minimumRelease = $releases[[string]$app.minimumSupportedWindowsRelease]
    if (-not $minimumRelease) { throw ('Unknown minimum Windows release in intune-app.json: "' + $app.minimumSupportedWindowsRelease + '".') }

    $restart = [string]$app.restartBehavior
    if (@('allow', 'basedOnReturnCode', 'suppress', 'force') -notcontains $restart) { $restart = 'basedOnReturnCode' }
    $maximumMinutes = 60
    if ([int]$app.maximumInstallationTimeInMinutes -ge 1 -and [int]$app.maximumInstallationTimeInMinutes -le 1440) { $maximumMinutes = [int]$app.maximumInstallationTimeInMinutes }

    if ($AssignIntent -ne 'none')
    {
        if ($AssignTo -eq 'Group' -and $GroupId -notmatch '^[0-9a-fA-F]{8}-([0-9a-fA-F]{4}-){3}[0-9a-fA-F]{12}$') { throw '-AssignTo Group needs -GroupId with the object ID (GUID) of the group.' }
        if ($AssignIntent -eq 'available' -and $AssignTo -eq 'AllDevices') { throw 'Intune cannot make an app "available" to all devices. Use -AssignTo AllUsers or a group.' }
    }
    $assignmentLabel = 'none (assign it in the Intune admin center)'
    if ($AssignIntent -ne 'none')
    {
        $assignmentLabel = $AssignIntent + ' for ' + $AssignTo
        if ($AssignTo -eq 'Group') { $assignmentLabel += ' ' + $GroupId }
    }
    $iconLabel = '(none)'
    if ($icon) { $iconLabel = [string]$app.icon }

    Write-Host ('  App             : ' + $app.displayName)
    Write-Host ('  Publisher       : ' + $publisher)
    Write-Host ('  Package         : ' + $app.intuneWinFile + '  (' + [math]::Round($encryptedSize / 1MB, 1) + ' MB)')
    Write-Host ('  Install         : ' + $app.installCommandLine)
    Write-Host ('  Uninstall       : ' + $app.uninstallCommandLine)
    Write-Host ('  Install context : ' + $experience)
    Write-Host ('  Architecture    : ' + $allowedArchitectures)
    Write-Host ('  Minimum Windows : ' + $app.minimumSupportedWindowsRelease)
    Write-Host ('  Detection       : ' + $app.detectionScript)
    Write-Host ('  Icon            : ' + $iconLabel)
    Write-Host ('  Assignment      : ' + $assignmentLabel)
    Write-Host ''

    if ($ValidateOnly)
    {
        # The result file is left alone: it may hold the app id of an earlier publication.
        Write-Ok 'Files and values are valid. Nothing was sent to Intune (-ValidateOnly).'
        Stop-Script 0
    }

    # ------------------------------------------------------------ sign-in
    if ([string]::IsNullOrWhiteSpace($TenantId)) { $TenantId = Read-Host 'Tenant ID or domain (for example contoso.onmicrosoft.com)' }
    if ([string]::IsNullOrWhiteSpace($ClientId)) { $ClientId = Read-Host 'Application (client) ID of your Entra app registration' }
    $TenantId = ([string]$TenantId).Trim()
    $ClientId = ([string]$ClientId).Trim()
    if (-not $TenantId -or -not $ClientId) { throw 'TenantId and ClientId are required.' }
    $script:Result.tenantId = $TenantId

    Write-Step 'Signing in to Microsoft Graph...'
    if ($DeviceCode) { Connect-WithDeviceCode } else { Connect-WithBrowser }
    Write-Ok ('Signed in to ' + $TenantId)

    # ------------------------------------------------------------ existing app with the same name
    Write-Step 'Looking for an app with the same name...'
    $filter = "isof('microsoft.graph.win32LobApp') and displayName eq '" + ([string]$app.displayName).Replace("'", "''") + "'"
    $found = Invoke-Graph -Method 'GET' -Path ('/deviceAppManagement/mobileApps?$filter=' + [uri]::EscapeDataString($filter))
    $existing = @($found.value)
    $targetId = $null
    if ($existing.Count -gt 0)
    {
        Write-Note ($existing.Count.ToString() + ' app(s) named "' + $app.displayName + '" already exist in this tenant (version: ' + (($existing | ForEach-Object { [string]$_.displayVersion }) -join ', ') + ').')
        $choice = $IfExists
        if ($choice -eq 'Ask')
        {
            if ($Force) { $choice = 'Fail' }
            else
            {
                $answer = Read-Host '  [U]pdate the existing app, create a [N]ew one with the same name, or [C]ancel? (U/N/C)'
                if ($answer -match '^\s*u') { $choice = 'Update' } elseif ($answer -match '^\s*n') { $choice = 'CreateNew' } else { $choice = 'Cancel' }
            }
        }
        if ($choice -eq 'Cancel')
        {
            Write-Note 'Cancelled. Nothing was published.'
            Save-Result 'cancelled' ''
            Stop-Script 2
        }
        if ($choice -eq 'Fail') { throw ('An app named "' + $app.displayName + '" already exists. Use -IfExists Update or -IfExists CreateNew.') }
        if ($choice -eq 'Update')
        {
            if ($existing.Count -gt 1) { throw 'More than one app has this name: update the right one in the Intune admin center, or use -IfExists CreateNew.' }
            $targetId = [string]$existing[0].id
        }
    }
    else { Write-Ok 'No app with this name yet.' }

    if (-not $Force)
    {
        Write-Host ''
        $verb = 'Create'
        if ($targetId) { $verb = 'Update' }
        $answer = Read-Host ($verb + ' the app "' + $app.displayName + '" in the tenant ' + $TenantId + ' now? (Y/N)')
        if ($answer -notmatch '^\s*(y|s)')
        {
            Write-Note 'Cancelled. Nothing was published.'
            Save-Result 'cancelled' ''
            Stop-Script 2
        }
    }

    # ------------------------------------------------------------ app
    $body = [ordered]@{
        '@odata.type'                  = '#microsoft.graph.win32LobApp'
        displayName                    = [string]$app.displayName
        description                    = $description
        publisher                      = $publisher
        displayVersion                 = [string]$app.appVersion
        notes                          = [string]$app.notes
        fileName                       = $contentName
        setupFilePath                  = $setupFile
        installCommandLine             = [string]$app.installCommandLine
        uninstallCommandLine           = [string]$app.uninstallCommandLine
        installExperience              = [ordered]@{ runAsAccount = $experience; deviceRestartBehavior = $restart; maxRunTimeInMinutes = $maximumMinutes }
        allowedArchitectures           = $allowedArchitectures
        applicableArchitectures        = 'none'
        minimumSupportedWindowsRelease = $minimumRelease
        allowAvailableUninstall        = ($app.allowAvailableUninstall -eq $true)
        detectionRules                 = @(
            [ordered]@{
                '@odata.type'         = '#microsoft.graph.win32LobAppPowerShellScriptDetection'
                enforceSignatureCheck = $false
                runAs32Bit            = $false
                scriptContent         = [Convert]::ToBase64String([System.IO.File]::ReadAllBytes($detection))
            }
        )
        returnCodes                    = @(
            @{ returnCode = 0; type = 'success' }, @{ returnCode = 1707; type = 'success' }, @{ returnCode = 3010; type = 'softReboot' },
            @{ returnCode = 1641; type = 'hardReboot' }, @{ returnCode = 1618; type = 'retry' }
        )
    }
    if ([string]$app.informationUrl -match '^https?://') { $body['informationUrl'] = [string]$app.informationUrl }
    if ($icon) { $body['largeIcon'] = [ordered]@{ type = 'image/png'; value = [Convert]::ToBase64String([System.IO.File]::ReadAllBytes($icon)) } }

    if ($targetId)
    {
        Write-Step 'Updating the settings of the existing app...'
        $null = Invoke-Graph -Method 'PATCH' -Path ('/deviceAppManagement/mobileApps/' + $targetId) -Body $body
        $script:Result.action = 'updated'
    }
    else
    {
        Write-Step 'Creating the app...'
        $created = Invoke-Graph -Method 'POST' -Path '/deviceAppManagement/mobileApps' -Body $body
        $targetId = [string]$created.id
        if (-not $targetId) { throw 'Intune did not return the id of the new app.' }
        $script:CreatedAppId = $targetId
        $script:Result.action = 'created'
    }
    $script:Result.appId = $targetId
    $script:Result.portalUrl = 'https://intune.microsoft.com/#view/Microsoft_Intune_Apps/SettingsMenu/~/0/appId/' + $targetId
    Write-Ok ('App id ' + $targetId)

    # ------------------------------------------------------------ content
    $appPath = '/deviceAppManagement/mobileApps/' + $targetId + '/microsoft.graph.win32LobApp'
    $version = Invoke-Graph -Method 'POST' -Path ($appPath + '/contentVersions') -Body @{}
    $versionId = [string]$version.id
    $fileBody = [ordered]@{
        '@odata.type' = '#microsoft.graph.mobileAppContentFile'; name = $contentName; size = $unencryptedSize; sizeEncrypted = $encryptedSize
        manifest = $null; isDependency = $false
    }
    $contentFile = Invoke-Graph -Method 'POST' -Path ($appPath + '/contentVersions/' + $versionId + '/files') -Body $fileBody
    $filePath = $appPath + '/contentVersions/' + $versionId + '/files/' + [string]$contentFile.id
    $contentFile = Wait-FileState -FilePath $filePath -Stage 'azureStorageUriRequest' -Minutes 10
    $sasUri = [string]$contentFile.azureStorageUri
    $sasIssued = Get-Date

    Write-Step ('Uploading ' + [math]::Round($encryptedSize / 1MB, 1) + ' MB to Intune...')
    $blockIds = New-Object System.Collections.Generic.List[string]
    $zip = [System.IO.Compression.ZipFile]::OpenRead($intuneWin)
    try
    {
        $contentEntry = $zip.Entries | Where-Object { ($_.FullName -replace '\\', '/') -ieq ('IntuneWinPackage/Contents/' + $contentName) } | Select-Object -First 1
        $source = $contentEntry.Open()
        try
        {
            $buffer = New-Object byte[] $BlockSize
            [int64]$sent = 0
            $lastShown = -1
            while ($true)
            {
                # A block is filled completely before it is sent (a zip stream may return less than asked).
                $filled = 0
                while ($filled -lt $buffer.Length)
                {
                    $read = $source.Read($buffer, $filled, $buffer.Length - $filled)
                    if ($read -le 0) { break }
                    $filled += $read
                }
                if ($filled -eq 0) { break }
                $data = $buffer
                if ($filled -lt $buffer.Length) { $data = New-Object byte[] $filled; [Array]::Copy($buffer, $data, $filled) }

                # The upload address is valid for a limited time: it is renewed every 7 minutes.
                if (((Get-Date) - $sasIssued).TotalMinutes -ge 7)
                {
                    $null = Invoke-Graph -Method 'POST' -Path ($filePath + '/renewUpload') -Body @{}
                    $contentFile = Wait-FileState -FilePath $filePath -Stage 'azureStorageUriRenewal' -Minutes 10
                    $sasUri = [string]$contentFile.azureStorageUri
                    $sasIssued = Get-Date
                }
                $blockId = [Convert]::ToBase64String([System.Text.Encoding]::ASCII.GetBytes('block-' + $blockIds.Count.ToString('000000')))
                Send-Block -SasUri $sasUri -BlockId $blockId -Data $data
                $blockIds.Add($blockId)
                $sent += $filled
                $percent = [int]([math]::Floor($sent * 100 / [math]::Max(1, $encryptedSize)))
                if ($percent -ge $lastShown + 10 -or $sent -ge $encryptedSize) { Write-Host ('  ' + $percent + ' %') -ForegroundColor Gray; $lastShown = $percent }
            }
            if ($sent -ne $encryptedSize) { throw ('The upload sent ' + $sent + ' bytes, but the package has ' + $encryptedSize + '.') }
        }
        finally { $source.Close() }
    }
    finally { $zip.Dispose() }

    $blockList = '<?xml version="1.0" encoding="utf-8"?><BlockList>' + (($blockIds | ForEach-Object { '<Latest>' + $_ + '</Latest>' }) -join '') + '</BlockList>'
    $answer = Invoke-Http -Method 'PUT' -Url ($sasUri + '&comp=blocklist') -Body ([System.Text.Encoding]::UTF8.GetBytes($blockList)) -ContentType 'application/xml' -TimeoutSeconds 300
    if ($answer.Status -ne 201) { throw ('The upload could not be finished (HTTP ' + $answer.Status + ').') }
    Write-Ok ('Uploaded in ' + $blockIds.Count + ' block(s)')

    Write-Step 'Waiting for Intune to confirm the content (this can take a few minutes)...'
    $commitBody = @{
        fileEncryptionInfo = [ordered]@{
            encryptionKey        = [string]$encryption.EncryptionKey
            macKey               = [string]$encryption.MacKey
            initializationVector = [string]$encryption.InitializationVector
            mac                  = [string]$encryption.Mac
            profileIdentifier    = [string]$encryption.ProfileIdentifier
            fileDigest           = [string]$encryption.FileDigest
            fileDigestAlgorithm  = [string]$encryption.FileDigestAlgorithm
        }
    }
    $null = Invoke-Graph -Method 'POST' -Path ($filePath + '/commit') -Body $commitBody
    $null = Wait-FileState -FilePath $filePath -Stage 'commitFile' -Minutes 60
    $null = Invoke-Graph -Method 'PATCH' -Path ('/deviceAppManagement/mobileApps/' + $targetId) -Body ([ordered]@{ '@odata.type' = '#microsoft.graph.win32LobApp'; committedContentVersion = $versionId })
    Write-Ok ('Content version ' + $versionId + ' is active')
    # From here on the app is complete: a later failure must not remove it.
    $script:CreatedAppId = $null

    # ------------------------------------------------------------ assignment (new apps only)
    if ($AssignIntent -ne 'none')
    {
        if ($script:Result.action -ne 'created') { Write-Note 'The existing app keeps its assignments: -AssignIntent only applies to a new app.' }
        else
        {
            Write-Step ('Assigning: ' + $assignmentLabel + '...')
            $target = @{ '@odata.type' = '#microsoft.graph.allLicensedUsersAssignmentTarget' }
            if ($AssignTo -eq 'AllDevices') { $target = @{ '@odata.type' = '#microsoft.graph.allDevicesAssignmentTarget' } }
            if ($AssignTo -eq 'Group') { $target = [ordered]@{ '@odata.type' = '#microsoft.graph.groupAssignmentTarget'; groupId = $GroupId } }
            $assignBody = @{
                mobileAppAssignments = @(
                    [ordered]@{
                        '@odata.type' = '#microsoft.graph.mobileAppAssignment'
                        intent        = $AssignIntent
                        target        = $target
                        settings      = [ordered]@{
                            '@odata.type' = '#microsoft.graph.win32LobAppAssignmentSettings'; notifications = 'showAll'
                            restartSettings = $null; installTimeSettings = $null; deliveryOptimizationPriority = 'notConfigured'
                        }
                    }
                )
            }
            try
            {
                $null = Invoke-Graph -Method 'POST' -Path ('/deviceAppManagement/mobileApps/' + $targetId + '/assign') -Body $assignBody
                $script:Result.assignment = $assignmentLabel
                Write-Ok 'Assigned'
            }
            catch
            {
                # The app itself is published: the assignment can be done in the admin center.
                Write-Note ('The app was published, but the assignment failed: ' + $_.Exception.Message)
                $script:Result.assignment = 'failed: ' + $_.Exception.Message
            }
        }
    }

    Save-Result 'published' ''
    Write-Host ''
    Write-Ok ('App ' + $script:Result.action + ': ' + $app.displayName)
    Write-Host ('         id: ' + $targetId)
    Write-Host ('         ' + $script:Result.portalUrl)
    Write-Host ''
    Write-Host 'Next steps' -ForegroundColor White
    Write-Host '  1. Open the link above (or https://intune.microsoft.com > Apps > Windows) and review the app.'
    if ($script:Result.assignment -and $script:Result.assignment -notlike 'failed*') { Write-Host '  2. Follow the installation status of the assignment before widening it.' }
    else { Write-Host '  2. Assign it to a pilot group before a broad deployment.' }
    Write-Host ''
    Stop-Script 0
}
catch
{
    $message = $_.Exception.Message
    Write-Host ''
    Write-Host ('  ERROR  ' + $message) -ForegroundColor Red
    # An app created by this run and left without content would be a broken entry in the tenant: remove it.
    if ($script:CreatedAppId)
    {
        try
        {
            $null = Invoke-Graph -Method 'DELETE' -Path ('/deviceAppManagement/mobileApps/' + $script:CreatedAppId)
            Write-Note 'The incomplete app was removed from Intune. Nothing was left behind.'
            $script:Result.appId = ''
            $script:Result.portalUrl = ''
            $script:Result.action = ''
        }
        catch { Write-Note ('The incomplete app ' + $script:CreatedAppId + ' could not be removed: delete it in the Intune admin center.') }
    }
    Write-Host ''
    Save-Result 'failed' $message
    Stop-Script 1
}
