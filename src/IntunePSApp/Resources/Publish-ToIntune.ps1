    Write-Host ''

    # ------------------------------------------------------------ package metadata and files
    $metadataPath = Join-Path $here 'intune-app.json'
    if (-not (Test-Path -LiteralPath $metadataPath)) { throw 'intune-app.json was not found next to this script.' }
    $app = Get-Content -LiteralPath $metadataPath -Raw -Encoding UTF8 | ConvertFrom-Json
    foreach ($required in 'displayName', 'intuneWinFile', 'detectionScript', 'installCommandLine', 'uninstallCommandLine')
    {
        if ([string]::IsNullOrWhiteSpace([string]$app.$required)) { throw ('intune-app.json is incomplete: "' + $required + '" is empty.') }
    }
    $script:Result.displayName = [string]$app.displayName
    $script:Result.appVersion = [string]$app.appVersion

    $intuneWin = Join-Path $here $app.intuneWinFile
    $detection = Join-Path $here $app.detectionScript
    foreach ($file in $intuneWin, $detection)
    {
        if (-not (Test-Path -LiteralPath $file -PathType Leaf)) { throw ('File not found: ' + $file) }
    }
    $icon = $null
    if (-not [string]::IsNullOrWhiteSpace([string]$app.icon))
    {
        $candidate = Join-Path $here $app.icon
        if ((Test-Path -LiteralPath $candidate -PathType Leaf) -and $candidate -match '\.png$') { $icon = $candidate }
    }
    if (-not [string]::IsNullOrWhiteSpace([string]$app.intuneWinSha256))
    {
        # Hashed with .NET: the file-hash cmdlet is missing when Windows PowerShell is started from PowerShell 7.
        $hashStream = [System.IO.File]::OpenRead($intuneWin)
        try { $hash = [System.BitConverter]::ToString([System.Security.Cryptography.SHA256]::Create().ComputeHash($hashStream)).Replace('-', '') }
        finally { $hashStream.Close() }
        if ($hash -ne $app.intuneWinSha256) { throw 'The .intunewin file does not match the SHA256 recorded when it was generated. Generate the package again.' }
    }
    if ((Get-Item -LiteralPath $intuneWin).Length -gt 30GB) { throw 'The package is larger than 30 GB, the limit of Intune for a Windows app.' }

    # The .intunewin is a zip: Detection.xml carries the encryption data, Contents holds the encrypted package.
    $zip = [System.IO.Compression.ZipFile]::OpenRead($intuneWin)
    try
    {
        $detectionEntry = $zip.Entries | Where-Object { ($_.FullName -replace '\\', '/') -ieq 'IntuneWinPackage/Metadata/Detection.xml' } | Select-Object -First 1
        if (-not $detectionEntry) { throw 'The .intunewin file has no Detection.xml: it is not a valid Intune package.' }
        $reader = New-Object System.IO.StreamReader($detectionEntry.Open(), [System.Text.Encoding]::UTF8)
        try { [xml]$detectionXml = $reader.ReadToEnd() } finally { $reader.Close() }
        $info = $detectionXml.ApplicationInfo
        $encryption = $info.EncryptionInfo
        foreach ($field in 'EncryptionKey', 'MacKey', 'InitializationVector', 'Mac', 'ProfileIdentifier', 'FileDigest', 'FileDigestAlgorithm')
        {
            if ([string]::IsNullOrWhiteSpace([string]$encryption.$field)) { throw ('The .intunewin file is incomplete: "' + $field + '" is missing in Detection.xml.') }
        }
        $contentName = [string]$info.FileName
        $contentEntry = $zip.Entries | Where-Object { ($_.FullName -replace '\\', '/') -ieq ('IntuneWinPackage/Contents/' + $contentName) } | Select-Object -First 1
        if (-not $contentEntry) { throw ('The .intunewin file has no content "' + $contentName + '".') }
        $encryptedSize = [int64]$contentEntry.Length
        $unencryptedSize = [int64]$info.UnencryptedContentSize
        $setupFile = [string]$info.SetupFile
    }
    finally { $zip.Dispose() }
    if ([string]::IsNullOrWhiteSpace($setupFile)) { $setupFile = 'Invoke-AppDeployToolkit.exe' }

    # ------------------------------------------------------------ values sent to Intune
    $publisher = [string]$app.publisher
    if ([string]::IsNullOrWhiteSpace($publisher)) { $publisher = [string]$app.displayName }
    $description = [string]$app.description
    if ([string]::IsNullOrWhiteSpace($description)) { $description = [string]$app.displayName }
    $experience = 'system'
