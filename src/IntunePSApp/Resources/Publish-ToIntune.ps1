function Set-Token($Response)
{
    $script:Token = @{
        AccessToken  = [string]$Response.access_token
        RefreshToken = [string]$Response.refresh_token
        ExpiresAt    = (Get-Date).AddSeconds([int]$Response.expires_in)
    }
}

function Invoke-TokenRequest([hashtable]$Fields, [switch]$AllowPending)
{
    $answer = Invoke-Http -Method 'POST' -Url ($LoginUrl.TrimEnd('/') + '/' + $TenantId + '/oauth2/v2.0/token') -Body (ConvertTo-FormBody $Fields) -ContentType 'application/x-www-form-urlencoded'
    $data = $null
    try { $data = $answer.Text | ConvertFrom-Json } catch { }
    if ($answer.Status -eq 200 -and $data -and $data.access_token) { return $data }
    if ($AllowPending -and $data -and ($data.error -eq 'authorization_pending' -or $data.error -eq 'slow_down')) { return $data }
    $description = 'HTTP ' + $answer.Status
    if ($data -and $data.error_description) { $description = ([string]$data.error_description -split "`r?`n")[0] }
    $help = Get-SignInHelp $description
    if ($help) { throw ('Sign-in failed. ' + $help + ' [' + $description + ']') }
    throw ('Sign-in failed: ' + $description)
}

function ConvertTo-Base64Url([byte[]]$Bytes) { return [Convert]::ToBase64String($Bytes).TrimEnd('=').Replace('+', '-').Replace('/', '_') }

# Browser sign-in: authorization code with PKCE, answered on a local port.
function Connect-WithBrowser
{
    $random = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    $bytes = New-Object byte[] 32
    $random.GetBytes($bytes)
    $verifier = ConvertTo-Base64Url $bytes
    $sha = [System.Security.Cryptography.SHA256]::Create()
    $challenge = ConvertTo-Base64Url ($sha.ComputeHash([System.Text.Encoding]::ASCII.GetBytes($verifier)))
    $random.GetBytes($bytes)
    $state = ConvertTo-Base64Url $bytes

    $probe = New-Object System.Net.Sockets.TcpListener([System.Net.IPAddress]::Loopback, 0)
    $probe.Start()
    $port = $probe.LocalEndpoint.Port
    $probe.Stop()
    $redirect = 'http://localhost:' + $port + '/'
    $listener = New-Object System.Net.HttpListener
    $listener.Prefixes.Add($redirect)
    $listener.Start()
    try
    {
        $query = @{
            client_id = $ClientId; response_type = 'code'; redirect_uri = $redirect; response_mode = 'query'; scope = $Scope
            state = $state; code_challenge = $challenge; code_challenge_method = 'S256'; prompt = 'select_account'
        }
        $pairs = foreach ($name in $query.Keys) { $name + '=' + [uri]::EscapeDataString([string]$query[$name]) }
        $authorize = $LoginUrl.TrimEnd('/') + '/' + $TenantId + '/oauth2/v2.0/authorize?' + ($pairs -join '&')
        Write-Note 'A browser window opens for the sign-in. This script waits up to 5 minutes.'
        Start-Process $authorize

        $pending = $listener.BeginGetContext($null, $null)
        if (-not $pending.AsyncWaitHandle.WaitOne(300000)) { throw 'The sign-in was not completed within 5 minutes (was the browser window closed?).' }
        $context = $listener.EndGetContext($pending)
        $answer = $context.Request.QueryString
        $page = '<html><body style="font-family:Segoe UI,sans-serif;margin:48px"><h2>J365 IntunePSApp</h2><p>The sign-in was received. You can close this tab and return to the PowerShell window.</p></body></html>'
        $pageBytes = [System.Text.Encoding]::UTF8.GetBytes($page)
        $context.Response.ContentType = 'text/html; charset=utf-8'
        $context.Response.OutputStream.Write($pageBytes, 0, $pageBytes.Length)
        $context.Response.Close()
    }
    finally { $listener.Stop(); $listener.Close() }

    if ($answer['error'])
    {
        $description = ([string]$answer['error_description'] -split "`r?`n")[0]
        $help = Get-SignInHelp $description
        if ($help) { throw ('Sign-in failed. ' + $help + ' [' + $description + ']') }
        throw ('Sign-in failed: ' + $answer['error'] + ' ' + $description)
    }
    if ([string]$answer['state'] -ne $state -or -not $answer['code']) { throw 'Sign-in failed: unexpected answer from the browser.' }
    Set-Token (Invoke-TokenRequest @{ grant_type = 'authorization_code'; client_id = $ClientId; code = $answer['code']; redirect_uri = $redirect; code_verifier = $verifier; scope = $Scope })
}

function Connect-WithDeviceCode
{
    $answer = Invoke-Http -Method 'POST' -Url ($LoginUrl.TrimEnd('/') + '/' + $TenantId + '/oauth2/v2.0/devicecode') -Body (ConvertTo-FormBody @{ client_id = $ClientId; scope = $Scope }) -ContentType 'application/x-www-form-urlencoded'
    $data = $null
    try { $data = $answer.Text | ConvertFrom-Json } catch { }
    if ($answer.Status -ne 200 -or -not $data -or -not $data.device_code)
    {
        $description = 'HTTP ' + $answer.Status
        if ($data -and $data.error_description) { $description = ([string]$data.error_description -split "`r?`n")[0] }
        $help = Get-SignInHelp $description
        if ($help) { throw ('Sign-in failed. ' + $help + ' [' + $description + ']') }
        throw ('Sign-in failed: ' + $description)
    }
    Write-Host ''
    Write-Host ('  ' + $data.message) -ForegroundColor White
    Write-Host ''
    $interval = [Math]::Max(1, [int]$data.interval)
    $deadline = (Get-Date).AddSeconds([int]$data.expires_in)
    while ((Get-Date) -lt $deadline)
    {
        Start-Sleep -Seconds $interval
        $token = Invoke-TokenRequest @{ grant_type = 'urn:ietf:params:oauth:grant-type:device_code'; client_id = $ClientId; device_code = $data.device_code } -AllowPending
        if ($token.access_token) { Set-Token $token; return }
        if ($token.error -eq 'slow_down') { $interval += 5 }
    }
    throw 'The code expired before the sign-in was completed.'
}

# A long upload can outlive the access token: it is renewed with the refresh token when 5 minutes are left.
function Get-AccessToken
{
    if (-not $script:Token) { throw 'Not signed in.' }
    if ((Get-Date) -gt $script:Token.ExpiresAt.AddMinutes(-5))
    {
        if (-not $script:Token.RefreshToken) { throw 'The sign-in expired and cannot be renewed. Run the script again.' }
        Set-Token (Invoke-TokenRequest @{ grant_type = 'refresh_token'; client_id = $ClientId; refresh_token = $script:Token.RefreshToken; scope = $Scope })
    }
    return $script:Token.AccessToken
}

# ---------------------------------------------------------------- Microsoft Graph

function Invoke-Graph
{
    param([string]$Method, [string]$Path, $Body)

    $url = $GraphUrl.TrimEnd('/') + '/beta' + $Path
    $bytes = $null
    if ($null -ne $Body) { $bytes = [System.Text.Encoding]::UTF8.GetBytes(($Body | ConvertTo-Json -Depth 12 -Compress)) }
    for ($attempt = 1; ; $attempt++)
    {
        $answer = Invoke-Http -Method $Method -Url $url -Headers @{ Authorization = 'Bearer ' + (Get-AccessToken) } -Body $bytes -ContentType 'application/json'
        if ($answer.Status -ge 200 -and $answer.Status -lt 300)
        {
            if ([string]::IsNullOrWhiteSpace($answer.Text)) { return $null }
            return ($answer.Text | ConvertFrom-Json)
        }
        # Throttling and temporary service errors are retried, as Microsoft Graph asks.
        if (($answer.Status -eq 429 -or $answer.Status -eq 503 -or $answer.Status -eq 504) -and $attempt -lt 6)
        {
            $wait = $answer.RetryAfter
            if ($wait -le 0) { $wait = 5 * $attempt }
            Write-Note ('Microsoft Graph asked to wait ' + $wait + ' s (HTTP ' + $answer.Status + ')...')
            Start-Sleep -Seconds ([Math]::Min($wait, 120))
            continue
        }
        $message = ''
        try { $message = [string](($answer.Text | ConvertFrom-Json).error.message) } catch { }
        if (-not $message) { $message = $answer.Text }
        if ($message.Length -gt 400) { $message = $message.Substring(0, 400) }
        $hint = ''
        if ($answer.Status -eq 403) { $hint = ' Your account needs an Intune role that can manage apps (for example Intune Administrator), and the app registration needs DeviceManagementApps.ReadWrite.All with admin consent.' }
        if ($answer.Status -eq 401) { $hint = ' The sign-in was not accepted by Microsoft Graph: check the permission and the admin consent of the app registration.' }
        throw ('Microsoft Graph answered HTTP ' + $answer.Status + ' to ' + $Method + ' ' + $Path + ': ' + $message + $hint)
    }
}

# Waits until Intune finishes a step of the content file (uploadState ends with Success).
function Wait-FileState([string]$FilePath, [string]$Stage, [int]$Minutes)
{
    $deadline = (Get-Date).AddMinutes($Minutes)
    while ((Get-Date) -lt $deadline)
    {
        $file = Invoke-Graph -Method 'GET' -Path $FilePath
        $state = [string]$file.uploadState
        if ($state -eq ($Stage + 'Success')) { return $file }
        if ($state -eq ($Stage + 'Failed') -or $state -eq ($Stage + 'TimedOut')) { throw ('Intune reported "' + $state + '" for the content of the app.') }
        Start-Sleep -Seconds 3
    }
    throw ('Intune did not finish "' + $Stage + '" within ' + $Minutes + ' minutes.')
}

function Send-Block([string]$SasUri, [string]$BlockId, [byte[]]$Data)
{
    $url = $SasUri + '&comp=block&blockid=' + [uri]::EscapeDataString($BlockId)
    for ($attempt = 1; ; $attempt++)
    {
        $failure = ''
        try
        {
            $answer = Invoke-Http -Method 'PUT' -Url $url -Headers @{ 'x-ms-blob-type' = 'BlockBlob' } -Body $Data -ContentType 'application/octet-stream' -TimeoutSeconds 600
            if ($answer.Status -eq 201) { return }
            $failure = 'HTTP ' + $answer.Status
        }
        catch { $failure = $_.Exception.Message }
        if ($attempt -ge 4) { throw ('The upload failed after ' + $attempt + ' attempts: ' + $failure) }
        Start-Sleep -Seconds (3 * $attempt)
    }
}

