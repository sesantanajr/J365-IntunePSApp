function Save-Result([string]$Status, [string]$ErrorText)
{
    $script:Result.status = $Status
    $script:Result.error = $ErrorText
    $script:Result.utc = (Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ')
