# One HTTP request that never throws for an HTTP error status: returns Status, Text and RetryAfter.
function Invoke-Http
{
    param([string]$Method, [string]$Url, [hashtable]$Headers, [byte[]]$Body, [string]$ContentType, [int]$TimeoutSeconds = 120)

    $request = [System.Net.HttpWebRequest][System.Net.WebRequest]::Create($Url)
    $request.Method = $Method
    $request.Timeout = $TimeoutSeconds * 1000
    $request.ReadWriteTimeout = $TimeoutSeconds * 1000
    $request.UserAgent = 'J365-IntunePSApp-Publish'
    $request.Accept = 'application/json'
    if ($Headers) { foreach ($name in $Headers.Keys) { $request.Headers[$name] = [string]$Headers[$name] } }
    if ($null -ne $Body)
    {
        if ($ContentType) { $request.ContentType = $ContentType }
        $request.ContentLength = $Body.Length
        $stream = $request.GetRequestStream()
        try { $stream.Write($Body, 0, $Body.Length) } finally { $stream.Close() }
    }
    elseif ($Method -ne 'GET' -and $Method -ne 'DELETE') { $request.ContentLength = 0 }

    $response = $null
    try { $response = $request.GetResponse() }
    catch
    {
        $failure = $_.Exception
        if ($failure -isnot [System.Net.WebException]) { $failure = $failure.GetBaseException() }
        if ($failure -is [System.Net.WebException] -and $failure.Response) { $response = $failure.Response }
        else { throw ('No answer from ' + ([uri]$Url).Host + ': ' + $failure.Message) }
    }
    try
    {
        $text = ''
        $responseStream = $response.GetResponseStream()
        if ($responseStream)
        {
            $reader = New-Object System.IO.StreamReader($responseStream, [System.Text.Encoding]::UTF8)
            $text = $reader.ReadToEnd()
            $reader.Close()
        }
        $retryAfter = 0
        $null = [int]::TryParse([string]$response.Headers['Retry-After'], [ref]$retryAfter)
        return [pscustomobject]@{ Status = [int]$response.StatusCode; Text = $text; RetryAfter = $retryAfter }
    }
    finally { $response.Close() }
}

function ConvertTo-FormBody([hashtable]$Fields)
{
    $pairs = foreach ($name in $Fields.Keys) { [uri]::EscapeDataString($name) + '=' + [uri]::EscapeDataString([string]$Fields[$name]) }
    return [System.Text.Encoding]::UTF8.GetBytes(($pairs -join '&'))
}

