<#
.SYNOPSIS
    Publishes the package of this folder to Microsoft Intune as a Windows app (Win32).

.DESCRIPTION
    Generated by J365 IntunePSApp (https://github.com/sesantanajr/J365-IntunePSApp).

    Everything is read from intune-app.json and from the .intunewin file of this folder: name, command
    lines, detection script, requirements, icon and the encryption data of the package. The script talks
    to Microsoft Graph directly, with your sign-in or the certificate of this computer: no PowerShell
    module is installed and no password or secret is stored by this script or by J365 IntunePSApp.

    Requirements
      - Windows PowerShell 5.1 or PowerShell 7.
      - An app registration in Microsoft Entra ID with DeviceManagementApps.ReadWrite.All (Microsoft Graph) and
        admin consent, used in one of two ways:
          * with YOUR sign-in: public client, redirect URI http://localhost, delegated permission; your account
            needs an Intune role that can create apps (for example Intune Administrator);
          * as the application, with -CertificateThumbprint: the application permission and the certificate of
            this computer (J365 IntunePSApp sets both up); no user and no secret.
        Step by step: https://github.com/sesantanajr/J365-IntunePSApp/blob/main/docs/INTUNE-PUBLISH.md

    What it does
      1. Checks every file before signing in (-ValidateOnly stops here).
      2. Signs in (browser window, a code with -DeviceCode, or the certificate of this computer with
         -CertificateThumbprint).
      3. Looks for an app with the same name. By default it asks what to do; see -IfExists.
      4. Creates the app, uploads the content and waits until Intune confirms it.
         If anything fails after the app was created, the incomplete app is removed again.
      5. Optionally assigns it (-AssignIntent). By default the app is created WITHOUT assignments.
      6. Writes publish-result.json in this folder (app id, link to the Intune admin center, or the error).

    Exit codes: 0 = published (or validated), 1 = failed, 2 = cancelled.

.PARAMETER TenantId
    Tenant ID (GUID) or domain, for example contoso.onmicrosoft.com.

.PARAMETER ClientId
    Application (client) ID of your app registration.

.PARAMETER DeviceCode
    Signs in with a device code instead of the browser window. Many organisations block this flow with
    Conditional Access; prefer the browser.

.PARAMETER CertificateThumbprint
    Connects as the application with this certificate of the current Windows user (Cert:\CurrentUser\My) instead
    of a user sign-in. The app registration needs the application permission DeviceManagementApps.ReadWrite.All
    with admin consent and the public part of the certificate; J365 IntunePSApp creates both (Settings >
    Microsoft Intune > Connect with a certificate).

.PARAMETER ValidateOnly
    Checks the files and shows what would be published, without connecting to Intune.

.PARAMETER IfExists
    What to do when an app with the same name already exists in the tenant:
    Ask (default), Fail, Update (new content and settings on the existing app, assignments are kept)
    or CreateNew (a second app with the same name).

.PARAMETER AssignIntent
    none (default), available or required. Only applied to an app created by this run.

.PARAMETER AssignTo
    AllUsers (default), AllDevices or Group. "available" cannot target AllDevices.

.PARAMETER GroupId
    Object ID of the Entra group, with -AssignTo Group.

.PARAMETER AppId
    Id of the Intune app to update (for example the previous version of this application). Its settings and content
    are replaced by this package; its assignments are kept. Without it, the app is looked up by its exact name.

.PARAMETER Force
    Does not ask for confirmation. With -IfExists Ask, an existing app then stops the script.

.PARAMETER Pause
    Waits for Enter before closing (used when J365 IntunePSApp opens this script in its own window).

.PARAMETER GraphUrl
    Microsoft Graph endpoint. Change it only for national clouds (for example https://graph.microsoft.us).

.PARAMETER LoginUrl
    Sign-in endpoint. Change it only for national clouds (for example https://login.microsoftonline.us).

.EXAMPLE
    .\Publish-ToIntune.ps1 -TenantId contoso.onmicrosoft.com -ClientId 00000000-0000-0000-0000-000000000000

.EXAMPLE
    .\Publish-ToIntune.ps1 -ValidateOnly

.EXAMPLE
    .\Publish-ToIntune.ps1 -TenantId contoso.onmicrosoft.com -ClientId <id> -CertificateThumbprint <thumbprint> -IfExists Update

.EXAMPLE
    .\Publish-ToIntune.ps1 -TenantId contoso.onmicrosoft.com -ClientId <id> -AssignIntent available -AssignTo Group -GroupId <group id>
#>
[CmdletBinding()]
