        {
            var a = new PackageAction { Type = def.Type, Phase = def.DefaultPhase };
            foreach (var f in def.Fields)
            {
                a.Params[f.Key] = f.Kind switch
                {
                    "choice" => f.Options[0],
                    "bool" => "true",
                    "number" => "5",
                    "code" => "Write-ADTLogEntry -Message 'custom'\nif ($true) { 'ok' }",
