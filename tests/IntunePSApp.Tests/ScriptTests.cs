    public class ActionCatalogTests
    {
        private static PackageAction Sample(ActionDef def)
        {
            var a = new PackageAction { Type = def.Type, Phase = def.DefaultPhase };
            foreach (var f in def.Fields)
            {
                a.Params[f.Key] = f.Kind switch
                {
                    "choice" => f.Options[0],
                    "bool" => "true",
                    "number" => "5",
                    "code" => "Write-ADTLogEntry -Message 'custom'\nif ($true) { 'ok' }",
                    _ => f.Key switch
                    {
                        "Key" => @"HKEY_LOCAL_MACHINE\SOFTWARE\Contoso",
                        "Source" => "file with 'quote'.exe",
                        "SuccessCodes" => "0, 1638",
                        "NamePattern" => "Old App*",
                        _ => "value with 'quote'"
                    }
                };
            }
            return a;
        }

        [Fact]
        public void Every_action_generates_valid_PowerShell_with_and_without_error_handling()
        {
            var body = new List<string> { "function Test-Actions", "{" };
            foreach (var def in ActionCatalog.All)
            {
                var a = Sample(def);
                Assert.Empty(ActionCatalog.Validate(a));
                a.ContinueOnError = true;
                body.AddRange(ActionCatalog.Generate(a));
                a.ContinueOnError = false;
                var lines = ActionCatalog.Generate(a);
                Assert.True(lines.Count >= 2, def.Type + " generated no code");
                Assert.StartsWith("    ## Action: ", lines[0]);
                body.AddRange(lines);
            }
            body.Add("}");
            Ps.AssertParses(string.Join("\r\n", body));
        }

        [Fact]
        public void Generated_code_uses_the_documented_toolkit_functions()
        {
            string Code(string type, params (string Key, string Value)[] p)
            {
                var a = new PackageAction { Type = type, ContinueOnError = false };
                foreach (var (k, v) in p) a.Params[k] = v;
                return string.Join("\n", ActionCatalog.Generate(a));
            }
            Assert.Contains("Start-ADTMsiProcess -Action 'Install' -FilePath (Join-Path -Path $adtSession.DirSupportFiles -ChildPath 'dep.msi') -SuccessExitCodes @(0, 1638)",
                Code("InstallDependency", ("Source", "dep.msi"), ("SuccessCodes", "0, 1638")));
            Assert.Contains("Start-ADTProcess -FilePath (Join-Path -Path $adtSession.DirSupportFiles -ChildPath 'VC_redist.x64.exe') -ArgumentList '/quiet /norestart' -SuccessExitCodes @(0, 1638, 3010)",
                Code("InstallDependency", ("Source", "VC_redist.x64.exe"), ("Arguments", "/quiet /norestart"), ("SuccessCodes", "0;1638 3010")));
            Assert.Contains("Set-ADTRegistryKey -LiteralPath 'HKLM:\\SOFTWARE\\Contoso' -Name 'Enabled' -Value 1 -Type DWord",
                Code("SetRegistry", ("Key", @"HKEY_LOCAL_MACHINE\SOFTWARE\Contoso"), ("Name", "Enabled"), ("Value", "1"), ("Type", "DWord")));
            Assert.Contains("-Value @('a', 'b') -Type MultiString", Code("SetRegistry", ("Key", @"HKLM:\SOFTWARE\C"), ("Name", "N"), ("Value", "a; b"), ("Type", "MultiString")));
            Assert.Contains("Remove-ADTRegistryKey -LiteralPath 'HKCU:\\Software\\C' -Recurse", Code("RemoveRegistry", ("Key", @"HKCU\Software\C")));
            Assert.Contains("GetFolderPath('CommonPrograms')", Code("CreateShortcut", ("Location", "StartMenu"), ("Name", "App"), ("Target", @"%ProgramFiles%\App\app.exe")));
            Assert.Contains("-ChildPath 'App.lnk'", Code("RemoveDesktopShortcut", ("Name", "App")));
            Assert.Contains("Set-Service -Name 'svc' -StartupType Disabled", Code("StopService", ("Name", "svc"), ("Mode", "StopDisable")));
            Assert.DoesNotContain("Set-Service", Code("StopService", ("Name", "svc"), ("Mode", "StopOnly")));
            Assert.Contains("-IgnoreExitCodes '*'", Code("RunProgram", ("Source", "Path"), ("FilePath", "x.exe")));
            Assert.DoesNotContain("-IgnoreExitCodes", Code("RunProgram", ("Source", "Path"), ("FilePath", "x.exe"), ("IgnoreExitCode", "false")));
            Assert.Contains("$adtSession.DirSupportFiles", Code("RunProgram", ("Source", "Package"), ("FilePath", "tool.exe")));
            Assert.Contains("-NoWait", Code("ShowMessage", ("Text", "Hi")));
            Assert.DoesNotContain("-NoWait", Code("ShowMessage", ("Text", "Hi"), ("Wait", "true")));
            Assert.Contains("Start-Sleep -Seconds 3600", Code("Wait", ("Seconds", "999999")));
        }

        [Fact]
        public void ContinueOnError_wraps_the_action_in_try_catch()
        {
            var a = new PackageAction { Type = "DeleteFile", ContinueOnError = true, Params = { ["Path"] = "x" } };
            string code = string.Join("\n", ActionCatalog.Generate(a));
            Assert.Contains("try", code);
            Assert.Contains("Write-ADTLogEntry -Message ('Action failed [Delete file]: ' + $_.Exception.Message) -Severity 2", code);
        }

        [Fact]
        public void Validate_reports_missing_and_invalid_values()
        {
            Assert.NotEmpty(ActionCatalog.Validate(new PackageAction { Type = "DeleteFile" }));
            Assert.NotEmpty(ActionCatalog.Validate(new PackageAction { Type = "Nope" }));
            Assert.NotEmpty(ActionCatalog.Validate(new PackageAction { Type = "SetRegistry", Params = { ["Key"] = @"SOFTWARE\NoHive", ["Name"] = "n" } }));
            Assert.NotEmpty(ActionCatalog.Validate(new PackageAction { Type = "UninstallApp", Params = { ["NamePattern"] = "*a*" } }));
            Assert.NotEmpty(ActionCatalog.Validate(new PackageAction { Type = "RunPowerShell", Params = { ["Code"] = "if ($true) {" } }));
            Assert.NotEmpty(ActionCatalog.Validate(new PackageAction { Type = "InstallDependency", Params = { ["Source"] = "a.exe", ["SuccessCodes"] = "zero" } }));
            Assert.Empty(ActionCatalog.Validate(new PackageAction { Type = "RunPowerShell", Params = { ["Code"] = "if ($true) { 'ok' }" } }));
        }

        [Fact]
        public void Normalize_converts_values_saved_by_version_1()
        {
            var shortcut = new PackageAction { Type = "CreateShortcut", Phase = "Bogus", Params = { ["Location"] = "Menu Iniciar (todos os usuários)" } };
            var service = new PackageAction { Type = "StopService", Params = { ["Mode"] = "Parar e deixar manual" } };
            var run = new PackageAction { Type = "RunProgram", Params = { ["Source"] = "Arquivo extra do pacote" } };
            var desktop = new PackageAction { Type = "CreateShortcut", Params = { ["Location"] = "Área de trabalho (todos os usuários)" } };
            foreach (var a in new[] { shortcut, service, run, desktop }) ActionCatalog.Normalize(a);
            Assert.Equal("StartMenu", shortcut.P("Location"));
            Assert.Equal("PostInstall", shortcut.Phase);
            Assert.Equal("StopManual", service.P("Mode"));
            Assert.Equal("Package", run.P("Source"));
            Assert.Equal("Desktop", desktop.P("Location"));
            ActionCatalog.Normalize(shortcut); // idempotent
            Assert.Equal("StartMenu", shortcut.P("Location"));
        }

