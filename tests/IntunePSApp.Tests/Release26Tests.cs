    [Fact]
    public void A_silent_package_never_makes_Intune_restart_the_device()
    {
        Assert.Equal("suppress", PackageBuilder.RestartBehavior(new PackageSettings { DeployMode = "Silent" }));
        Assert.Equal("basedOnReturnCode", PackageBuilder.RestartBehavior(new PackageSettings { DeployMode = "Auto" }));
    }

    [Fact]
    public void Metadata_of_a_silent_package_hides_the_toasts_and_the_restart()
    {
        using var tmp = new TempFolder();
        var s = Fakes.Settings();
        s.DeployMode = "Silent";
        var r = new BuildResult { PackageFolder = tmp.Path, IntuneFolder = tmp.Path, IntuneWinFile = "app.intunewin", DetectionScript = "detect.ps1" };
        typeof(PackageBuilder).GetMethod("WriteCompanions", BindingFlags.Static | BindingFlags.NonPublic).Invoke(null, new object[] { s, r });
        using var json = JsonDocument.Parse(File.ReadAllText(r.MetadataFile));
        Assert.Equal("hideAll", json.RootElement.GetProperty("notifications").GetString());
        Assert.Equal("suppress", json.RootElement.GetProperty("restartBehavior").GetString());
    }

    [Fact]
    public void The_publication_assigns_with_the_toasts_of_the_package()
    {
        string script = PackageBuilder.EmbeddedText("Publish-ToIntune.ps1");
        Assert.Contains("notifications = $notifications", script);
        Assert.DoesNotContain("notifications = 'showAll'", script);
        Assert.Contains("$notifications = [string]$app.notifications", script);
        Ps.AssertParses(script);
    }

    [Fact]
    public void A_silent_script_has_no_deferral_message_countdown_or_restart_prompt()
    {
        var s = Fakes.Settings();
        s.DeployMode = "Silent";
        s.AllowDefer = true;
        s.WelcomeMessage = "Save your work";
        s.CompletionMessage = "Done";
        s.RestartPrompt = true;
        string script = ScriptGenerator.DeployScript(Fakes.Template, s, "setup.exe");
        Assert.DoesNotContain("AllowDefer", script);
        Assert.DoesNotContain("PersistPrompt", script);
        Assert.DoesNotContain("CustomText", script);
        Assert.DoesNotContain("CloseProcessesCountdown", script);
        Assert.DoesNotContain("Show-ADTInstallationPrompt", script);
        Assert.DoesNotContain("Show-ADTInstallationRestartPrompt", script);
        // The applications in use are still closed (silently, by the toolkit) before the installation.
        Assert.Contains("$saiwParams.Add('CloseProcesses', $adtSession.AppProcessesToClose)", script);
        Ps.AssertParses(script);

        s.DeployMode = "Auto";
        string interactive = ScriptGenerator.DeployScript(Fakes.Template, s, "setup.exe");
        Assert.Contains("AllowDefer = $true", interactive);
        Assert.Contains("Show-ADTInstallationRestartPrompt", interactive);
    }

