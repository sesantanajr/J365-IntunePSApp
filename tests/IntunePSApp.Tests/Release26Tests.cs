    [Fact]
    public void Batch_item_states_have_texts_in_both_languages()
    {
        foreach (var code in new[] { Loc.EnglishCode, Loc.PortugueseCode })
            Lang.With(code, () =>
            {
                foreach (BatchState state in System.Enum.GetValues(typeof(BatchState)))
                    Assert.True(Loc.Instance.Has("Batch_State_" + state), $"Batch_State_{state} ({code})");
            });
    }

    [Fact]
    public void Ticking_an_application_for_the_batch_notifies_the_catalog()
    {
        var app = App("Contoso.Tick", new CatalogInstaller { Type = "msi", Arch = "x64" });
        int raised = 0;
        void Handler(CatalogApp a) { if (a == app) raised++; }
        CatalogApp.QueuedChanged += Handler;
        try
        {
            app.IsQueued = true;
            app.IsQueued = true;   // no change, no event
            app.IsQueued = false;
        }
        finally { CatalogApp.QueuedChanged -= Handler; }
        Assert.Equal(2, raised);
    }

    private static string T(string key) => Loc.T(key);
