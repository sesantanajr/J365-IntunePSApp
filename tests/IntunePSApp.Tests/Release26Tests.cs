    [Fact]
    public void Automatic_toasts_leave_projects_and_revision_records_as_they_were_before_2_6()
    {
        // A package generated by 2.5.1 has no such setting: its revision record must still match after the update.
        var s = Fakes.Settings();
        Assert.DoesNotContain("IntuneNotifications", JsonSerializer.Serialize(s, Json.Options));
        Assert.Null(new AppConfig().NewPackage().IntuneNotifications);
        Assert.Null(new AppConfig { IntuneNotifications = "" }.NewPackage().IntuneNotifications);
        string before = PackageRevision.Fingerprint(s);
        s.IntuneNotifications = "hideAll";
        Assert.Contains("IntuneNotifications", JsonSerializer.Serialize(s, Json.Options));
        Assert.NotEqual(before, PackageRevision.Fingerprint(s));
        var reloaded = JsonSerializer.Deserialize<PackageSettings>(JsonSerializer.Serialize(s, Json.Options), Json.Options);
        Assert.Equal("hideAll", reloaded.IntuneNotifications);
    }

