    [Fact]
    public void The_generic_icon_of_setup_programs_is_recognised_and_application_icons_are_not()
    {
        using var tmp = new TempFolder();
        // The reference thumbnail drawn at 256 px, as Windows extracts a 32 px icon at that size.
        string generic = Path.Combine(tmp.Path, "generic.png");
        using (var small = new System.Drawing.Bitmap(16, 16))
        {
            var t = ImageTools.GenericSetupThumbnail;
            for (int y = 0, i = 0; y < 16; y++)
                for (int x = 0; x < 16; x++, i += 3) small.SetPixel(x, y, System.Drawing.Color.FromArgb(t[i], t[i + 1], t[i + 2]));
            using var big = new System.Drawing.Bitmap(256, 256);
            using (var g = System.Drawing.Graphics.FromImage(big))
            {
                g.InterpolationMode = System.Drawing.Drawing2D.InterpolationMode.NearestNeighbor;
                g.PixelOffsetMode = System.Drawing.Drawing2D.PixelOffsetMode.Half;
                g.DrawImage(small, 0, 0, 256, 256);
            }
            big.Save(generic, System.Drawing.Imaging.ImageFormat.Png);
        }
        Assert.True(ImageTools.IsGenericSetupIcon(generic));

        string tile = Path.Combine(tmp.Path, "tile.png");
        ImageTools.SaveInitialsIcon("WinMerge", "#0A5CA8", tile);
        Assert.False(ImageTools.IsGenericSetupIcon(tile));
        string white = Path.Combine(tmp.Path, "white.png");
        using (var w = new System.Drawing.Bitmap(64, 64))
        {
            using (var g = System.Drawing.Graphics.FromImage(w)) g.Clear(System.Drawing.Color.White);
            w.Save(white, System.Drawing.Imaging.ImageFormat.Png);
        }
        Assert.False(ImageTools.IsGenericSetupIcon(white));
        Assert.False(ImageTools.IsGenericSetupIcon(Path.Combine(tmp.Path, "missing.png")));
    }

