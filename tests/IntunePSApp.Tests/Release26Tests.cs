    private static CatalogApp App(string id, params CatalogInstaller[] installers) => new CatalogApp
    {
        Id = id, Name = id.Split('.').Last(), Publisher = "Contoso", Version = "1.0", Installers = installers.ToList()
    };

    [Fact]
    public void A_batch_plans_each_application_once_with_the_installer_the_editor_would_choose()
    {
        var app = App("Contoso.App",
            new CatalogInstaller { Type = "nullsoft", Arch = "x64", Scope = "user", Url = "https://example.com/u.exe" },
            new CatalogInstaller { Type = "wix", Arch = "x64", Scope = "machine", Url = "https://example.com/m.msi" },
            new CatalogInstaller { Type = "msix", Arch = "x64", Url = "https://example.com/a.msix" });
        var none = App("Contoso.Store", new CatalogInstaller { Type = "msix", Arch = "x64" });
        var items = BatchPackager.Plan(new[] { app, app, none }, new AppConfig { PreferredArch = "x64", PreferredLocale = "en-US" });
        Assert.Equal(2, items.Count);
        Assert.Equal("wix", items[0].Installer.Type);
        Assert.Null(items[1].Installer);
        Assert.Equal(BatchState.Waiting, items[0].State);
    }

    [Fact]
    public void Batch_choices_replace_the_company_defaults_and_the_rest_comes_from_the_installer()
    {
        var cfg = new AppConfig { CompanyName = "Old", DeployMode = "Auto", LogoPath = @"C:\logo.png", AccentColor = "#112233", DeferTimes = 3 };
        var info = new InstallerInfo { Path = @"C:\setup.exe", Type = "EXE", AppName = "Contoso App", AppVersion = "2.0", InstallArgs = "/S", UninstallPattern = "Contoso App*", CatalogId = "Contoso.App", CatalogMatch = "download" };
        var s = BatchPackager.Settings(info, cfg, new BatchOptions { CompanyName = " Jornada 365 ", DeployMode = "Silent", IntuneNotifications = "nonsense", AllowDefer = true, DeferTimes = 500, Owner = "TI" });
        Assert.Equal("Jornada 365", s.CompanyName);
        Assert.Equal("Silent", s.DeployMode);
        Assert.Null(s.IntuneNotifications);                   // unknown value: automatic (hidden for silent)
        Assert.Equal("hideAll", PackageBuilder.IntuneNotifications(s));
        Assert.Equal(99, s.DeferTimes);
        Assert.Equal("TI", s.Owner);
        Assert.Equal(@"C:\logo.png", s.LogoPath);              // what the batch does not set stays the company default
        Assert.Equal("#112233", s.AccentColor);
        Assert.Equal("Contoso App", s.AppName);                // and the application comes from the analysis
        Assert.Equal("Contoso App*", s.DetectionNamePattern);
        Assert.Equal("Contoso.App", s.CatalogId);

        var unknownMode = BatchPackager.Settings(info, cfg, new BatchOptions { DeployMode = "Loud" });
        Assert.Equal("Auto", unknownMode.DeployMode);
    }

    [Fact]
    public void A_batch_never_builds_an_exe_whose_silent_switches_are_unknown()
    {
        var s = Fakes.Settings();
        s.InstallArgs = "";
        var blockers = BatchPackager.Blockers(s, new ValidationResult(), null);
        Assert.Contains(T("Batch_NoSilentArgs"), blockers);

        s.InstallArgs = "/S";
        Assert.DoesNotContain(T("Batch_NoSilentArgs"), BatchPackager.Blockers(s, new ValidationResult(), null));
        var msi = Fakes.Settings("MSI");
        Assert.DoesNotContain(T("Batch_NoSilentArgs"), BatchPackager.Blockers(msi, new ValidationResult(), null));
    }

