    // ------------------------------------------------------------------ database knowledge

    [Fact]
    public void Inno_rows_take_the_install_mode_of_their_scope()
    {
        Assert.EndsWith("/CURRENTUSER", CatalogService.SilentArgsFor(new CatalogInstaller { Type = "inno", Scope = "user" }));
        Assert.EndsWith("/ALLUSERS", CatalogService.SilentArgsFor(new CatalogInstaller { Type = "inno", Scope = "machine" }));
        Assert.DoesNotContain("/ALLUSERS", CatalogService.SilentArgsFor(new CatalogInstaller { Type = "inno", Scope = "user" }));
        Assert.DoesNotContain("/CURRENTUSER", CatalogService.SilentArgsFor(new CatalogInstaller { Type = "inno" }));
        // A mode given by the manifest is never doubled or contradicted.
        string given = CatalogService.SilentArgsFor(new CatalogInstaller { Type = "inno", Scope = "user", Custom = "/CURRENTUSER" });
        Assert.Single(System.Text.RegularExpressions.Regex.Matches(given, "/CURRENTUSER"));
        Assert.DoesNotContain("/CURRENTUSER", CatalogService.SilentArgsFor(new CatalogInstaller { Type = "inno", Scope = "user", Custom = "/ALLUSERS" }));
    }

    [Theory]
    [InlineData("Microsoft Windows Desktop Runtime 10.0.15 (x64)", true)]
    [InlineData("Microsoft Windows Desktop Runtime - 10.0.0 (x64)", true)]
    [InlineData("Microsoft Windows Desktop Runtime - 8.0.10 (x64)", false)]
    [InlineData("Microsoft Windows Desktop Runtime - 9.0.10 (x86)", false)]
    public void The_curated_name_of_the_NET_10_desktop_runtime_matches_what_it_registers(string registered, bool expected)
    {
        using var stream = typeof(PackageBuilder).Assembly.GetManifestResourceStream("curated.json");
        var curated = JsonSerializer.Deserialize<CuratedFile>(stream, Json.Options);
        string pattern = curated.Apps["Microsoft.DotNet.DesktopRuntime.10"].NamePattern;
        Assert.Equal(expected, InstallerAnalyzer.WildcardToRegex(pattern).IsMatch(registered));
    }

